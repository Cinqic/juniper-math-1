@dataclass(frozen=True)
class CorpusLine:
    category: str
    text: str


def category_counts(total_lines: int = DEFAULT_TOTAL_LINES) -> dict[str, int]:
    return {cat: round(total_lines * prop) for cat, prop in CATEGORY_PROPORTIONS.items()}


def generate_corpus(seed: int = MASTER_SEED, total_lines: int = DEFAULT_TOTAL_LINES) -> Iterator[CorpusLine]:
    """Deterministically generate the full tokenizer-training corpus.

    Categories are generated and interleaved in a fixed, sorted order so the
    output is byte-identical across runs given the same (seed, total_lines).
    """
    counts = category_counts(total_lines)
    for category in sorted(_GENERATORS):
        rng = _rng_for(category, seed)
        generator = _GENERATORS[category]
        for text in generator(rng, counts[category]):
            yield CorpusLine(category=category, text=text)


def write_corpus(path, seed: int = MASTER_SEED, total_lines: int = DEFAULT_TOTAL_LINES) -> int:
    """Write one line of text per corpus line to ``path``. Returns line count."""
    n = 0
    with open(path, "w", encoding="utf-8") as handle:
        for line in generate_corpus(seed=seed, total_lines=total_lines):
            text = line.text.replace("\n", " ").strip()
            if not text:
                continue
            handle.write(text + "\n")
            n += 1
    return n
