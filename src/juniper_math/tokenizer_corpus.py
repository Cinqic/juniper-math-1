# Category proportions of the tokenizer-training corpus. Chosen to reflect
# Juniper Math 1's role as a math *specialist* that still understands the
# ordinary English surrounding math problems (Phase 2 spec Sec. 10, 13):
# natural-language word problems and explanations get the largest shares
# (that is most of what the model reads at inference time), numeric/symbolic
# categories get enough coverage to teach notation without letting numeric
# sludge dominate (Sec. 12), and tool syntax / errors get a small but
# guaranteed-nonzero share since Phase 3 depends on these strings tokenizing
# cleanly. Must sum to 1.0 exactly (checked in tests/test_tokenizer_corpus.py).
