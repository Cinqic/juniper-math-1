"""Deterministic synthetic corpus generator for Phase 2 tokenizer training.

This is NOT the Phase 4 model-training corpus. Its only job is to teach a
BPE tokenizer realistic mathematical-language *segmentation* — enough
linguistic and symbolic diversity to produce sensible vocabulary pieces,
not a capability benchmark. See docs/RESEARCH_NOTES.md and
reports/PHASE2_REPORT.md for the corpus philosophy.

Every category generator is a pure function of an integer seed: same seed
and category always produce byte-identical output, so the corpus (and the
tokenizer trained from it) is reconstructible from this file alone plus the
seed recorded in config/tokenizer.yaml. Nothing here reads the clock, the
network, or global ``random`` state.
"""

